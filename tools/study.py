#!/usr/bin/env python3
"""Study-material helper for the textbook ripper.

Commands
--------
  sections BOOK [UNIT]        page map of each unit's sections (from the OCR text)
  text BOOK FIRST [LAST]      print OCR text of PDF pages FIRST..LAST
  images BOOK FIRST [LAST] [--dpi 60] [--out DIR]
                              render pages to PNG (to look at pictures / layout)
  pinyin TEXT...              textbook-style pinyin for Chinese sentences
  render SPEC.json [...]      render study-material spec(s) to Markdown

Specs live in tools/specs/<book>/<kind>-unit-NN.json and render to
study/<book>/<kind>/unit-NN-<title>.md. Every Chinese string in a spec gets pinyin:
the spec's own "py" (use the book's printed pinyin when it has one), else
generated by pinyin_util. Chinese inside English text is annotated inline.
See .claude/skills/study-material/SKILL.md for the spec format.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import paths

OUT_ROOT = paths.CACHE
SPEC_ROOT = paths.SPECS
STUDY_ROOT = paths.STUDY

SECTION_PATTERNS = [
    ("unit title page", r"^第.{1,2}单元$"),
    ("warm-up 导入", r"WARM-UP"),
    ("brainstorm 头脑风暴", r"BRAINSTORM"),
    ("word power 生词总动员", r"WORD POWER"),
    ("vocabulary list 生词大盘点", r"VOCABULARY LIST"),
    ("tasks & activities 任务及活动", r"TASKS AND ACTIVITIES"),
    ("task demonstration 任务示范 (dialogue/text)", r"Task Demonstration"),
    ("step-by-step tasks 分步任务活动 (pattern drills)", r"Perform the Tasks Step by Step|分步任务活动"),
    ("comprehensive tasks 综合任务活动", r"Comprehensive Tasks|综合任务活动"),
    ("grammar notes 语法点注释", r"GRAMMAR NOTES"),
    ("review tasks 学习后任务", r"REVIEW TASK"),
    ("self-evaluation 自我评估", r"SELF-EVALUATION"),
    ("choose and test 选一选，测一测 (quiz)", r"Choose and test|选一选"),
    ("cultural notes 文化小贴士", r"CULTURAL NOTES"),
    ("listening scripts & answers 录音文本及答案", r"Listening Scripts"),
    ("glossary 词语总表", r"词语总表"),
]


# ------------------------------------------------------------------ page index

def page_texts(book: str) -> dict[int, str]:
    txt = (OUT_ROOT / book / f"{book}.txt").read_text(encoding="utf-8")
    pages = {}
    for m in re.finditer(r"===== PDF page (\d+)[^\n]*=====\n(.*?)(?======|\Z)", txt, re.S):
        pages[int(m.group(1))] = m.group(2)
    return pages


def printed_numbers(book: str) -> dict[int, str]:
    txt = (OUT_ROOT / book / f"{book}.txt").read_text(encoding="utf-8")
    return {int(m.group(1)): m.group(2) for m in re.finditer(r"===== PDF page (\d+) \(printed p\. (\d+)\)", txt)}


def unit_starts(book: str) -> dict[int, int]:
    """unit number -> PDF page of the unit's title page."""
    starts = {}
    for p, t in page_texts(book).items():
        lines = [l.strip() for l in t.strip().splitlines()[:4]]
        if lines and re.fullmatch(r"第.{1,2}单元", lines[0]):
            m = re.search(r"Unit\s*(\d+)", " ".join(lines[1:3]))
            if m:
                starts.setdefault(int(m.group(1)), p)
    return dict(sorted(starts.items()))


def unit_range(book: str, unit: int) -> tuple[int, int]:
    starts = unit_starts(book)
    texts = page_texts(book)
    first = starts[unit]
    later = [p for u, p in starts.items() if u > unit]
    if later:
        last = min(later) - 1
    else:  # last unit: stop at the back matter
        back = [p for p, t in texts.items() if p > first and re.search(r"Listening Scripts|词语总表|录音文本", t)]
        last = (min(back) - 1) if back else max(texts)
    return first, last


def sections(book: str, unit: int) -> list[tuple[str, int]]:
    first, last = unit_range(book, unit)
    texts = page_texts(book)
    found = []
    for p in range(first, last + 1):
        for name, pat in SECTION_PATTERNS:
            if re.search(pat, texts.get(p, ""), re.M) and not any(n == name for n, _ in found):
                found.append((name, p))
    return found


# ---------------------------------------------------------------------- render

GENERATED: list[tuple[str, str]] = []   # (zh, generated pinyin) for review


def _pinyin(zh: str) -> str:
    import pinyin_util
    py = pinyin_util.sentence_pinyin(zh)
    GENERATED.append((zh, py))
    return py


RUBY_FAILS: list[tuple[str, str]] = []   # (zh, py) pairs that couldn't be aligned


def _ruby(zh: str, py: str) -> str | None:
    """Interlinear pinyin (HTML ruby), or None if the pinyin doesn't line up with the characters."""
    import pinyin_util
    html_ = pinyin_util.ruby_html(zh, py)
    if html_ is None:
        RUBY_FAILS.append((zh, py))
    return html_


def _inline(text: str) -> str:
    import pinyin_util
    return pinyin_util.annotate_inline(text) if text else ""


def zh_lines(obj, quote: bool = False, bullet: str = "") -> list[str]:
    """Chinese + pinyin + English as consecutive lines."""
    if isinstance(obj, str):
        obj = {"zh": obj}
    zh, en = obj.get("zh", ""), obj.get("en", "")
    py = obj.get("py") or (_pinyin(zh) if zh else "")
    lines = []
    if zh:
        ruby = _ruby(zh, py)
        if ruby:
            lines.append(ruby)              # characters with pinyin aligned word by word
        else:
            lines.append(f"**{zh}**")
            lines.append(f"*{py}*")
    if en:
        lines.append(_inline(en))
    pre = "> " if quote else ""
    out = []
    for i, l in enumerate(lines):
        lead = bullet if (i == 0 and bullet) else (" " * len(bullet) if bullet else "")
        out.append(f"{pre}{lead}{l}" + ("  " if i < len(lines) - 1 else ""))
    return out


def heading(level: int, obj: dict, prefix: str = "") -> str:
    zh, en = obj.get("zh", ""), obj.get("en", "")
    py = obj.get("py") or (_pinyin(zh).rstrip(".") if zh else "")
    parts = [p for p in (f"{zh} ({py})" if zh else "", _inline(en)) if p]
    return f"{'#' * level} {prefix}{' — '.join(parts)}"


def render_blocks(blocks: list[dict]) -> list[str]:
    out = []
    n = 0
    for b in blocks:
        t = b.get("type", "text")
        if t == "text":
            out += zh_lines(b) + [""]
        elif t == "pattern":
            zh_p = b["zh"]
            if re.search(r"[\u3400-\u9fff]", zh_p):
                py_p = b.get("py") or _pinyin(zh_p)
                r = _ruby(zh_p, py_p)
                zh_p = r if r else zh_p + f"  \n> *{py_p}*"
            out += ["> **Pattern:** " + zh_p
                    + (f"  \n> {_inline(b['en'])}" if b.get("en") else ""), ""]
        elif t == "example":
            n += 1
            out += zh_lines(b, bullet=f"{n}. ") + [""]
        elif t == "dialogue":
            for line in b["lines"]:
                sp = line.get("speaker", "")
                sp_py = line.get("speaker_py", "")
                label = (_ruby(sp, sp_py) or f"{sp} ({sp_py})") if sp_py else sp
                body = zh_lines(line)
                body[0] = f"{label}: {body[0]}" if label else body[0]
                out += body + [""]
        elif t == "note":
            out += [f"> 💡 {_inline(b['en'])}", ""]
        elif t == "picture":
            out += [f"🖼️ *Picture: {_inline(b['en'])}*", ""]
        elif t == "list":
            for item in b["items"]:
                out += zh_lines(item, bullet="- ")
            out += [""]
        else:
            raise ValueError(f"unknown block type {t!r}")
    return out


def render_spec(spec: dict) -> str:
    book, unit = spec["book"], spec["unit"]
    title = spec["title"]
    kind = spec.get("kind", "grammar")
    kind_title = {"grammar": "Grammar & Sentence Patterns"}.get(kind, spec.get("kind_title", kind.title()))
    L = [heading(1, {"zh": title["zh"], "en": f"{title['en']}"}, f"{book} · Unit {unit}: "),
         "", f"**{kind_title}**" + (f" · source: {spec['source']}" if spec.get("source") else ""), ""]
    if spec.get("intro"):
        L += [_inline(spec["intro"]), ""]

    if spec.get("key_sentences"):
        L += [heading(2, {"zh": "重点语句", "en": "Key sentences"}), ""]
        for i, s in enumerate(spec["key_sentences"], 1):
            L += zh_lines(s, bullet=f"{i}. ") + [""]

    if spec.get("grammar"):
        L += [heading(2, {"zh": "语法点注释", "en": "Grammar notes"}), ""]
        for i, g in enumerate(spec["grammar"], 1):
            L += [heading(3, g["title"], f"{i}. "), ""]
            L += render_blocks(g.get("body", []))

    answers = []
    if spec.get("exercises"):
        L += [heading(2, {"zh": "练习", "en": "Practice"}), ""]
        for i, ex in enumerate(spec["exercises"], 1):
            L += [heading(3, ex["title"], f"Exercise {i}. "), ""]
            if ex.get("activity"):
                a = ex["activity"]
                L += [f"*{a['zh']} ({a.get('py') or _pinyin(a['zh']).rstrip('.')}) — {a['en']}*", ""]
            if ex.get("instructions"):
                L += zh_lines(ex["instructions"]) + [""]
            L += render_blocks(ex.get("body", []))
            ex_answers = []
            for j, item in enumerate(ex.get("items", []), 1):
                label = item.get("label", chr(96 + j))
                if item.get("picture"):
                    L += [f"**({label})** 🖼️ *{_inline(item['picture'])}*  "]
                else:
                    L += [f"**({label})**  "]
                if item.get("prompt"):
                    p = item["prompt"]
                    L += (zh_lines(p) if p.get("zh") else [_inline(p.get("en", ""))]) + [""]
                L += ["✏️ ________________________________________", ""]
                if item.get("answer"):
                    ex_answers.append((label, item["answer"], item.get("answer_note")))
            if ex_answers or ex.get("answer_note"):
                answers.append((i, ex["title"], ex_answers, ex.get("answer_note")))

    if spec.get("quiz"):
        q = spec["quiz"]
        L += [heading(2, {"zh": "选一选，测一测", "en": "Self-test"}), ""]
        if q.get("instructions"):
            L += zh_lines(q["instructions"]) + [""]
        qa = []
        for i, item in enumerate(q["questions"], 1):
            L += [f"**Question {i}**", ""]
            if item.get("question"):
                L += zh_lines(item["question"]) + [""]
            for k, opt in enumerate(item["options"]):
                L += zh_lines(opt, bullet=f"- {'ABCD'[k]}. ") + [""]
            qa.append((str(i), [{"en": f"**{'ABCD'[item['answer']]}** — {item.get('explain', '')}",
                                 **({"zh": item['options'][item['answer']]['zh'],
                                     "py": item['options'][item['answer']].get('py')} if item.get('show_answer_text', True) else {})}],
                       None))
        answers.append(("quiz", {"zh": "选一选，测一测", "en": "Self-test"}, qa, q.get("answer_note")))

    if answers:
        L += ["---", "", heading(2, {"zh": "答案", "en": "Answer key"}), "",
              "_Try the exercises first — click to reveal._", ""]
        for idx, title, items, note in answers:
            name = "Self-test" if idx == "quiz" else f"Exercise {idx}"
            L += [f"<details><summary><b>{name}: {title.get('en', '')}</b></summary>", ""]
            if note:
                L += [_inline(note), ""]
            for label, ans_list, ans_note in items:
                if isinstance(ans_list, dict):
                    ans_list = [ans_list]
                first = True
                for ans in ans_list:
                    body = zh_lines(ans) if ans.get("zh") else [_inline(ans.get("en", ""))]
                    lead = f"**({label})** " if first else "&nbsp;&nbsp;&nbsp;&nbsp;"
                    body[0] = lead + body[0]
                    L += body + [""]
                    first = False
                if ans_note:
                    L += [f"> 💡 {_inline(ans_note)}", ""]
            L += ["</details>", ""]
    return "\n".join(L).rstrip() + "\n"


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def out_path(spec: dict) -> Path:
    """study/<Book>/<kind>/unit-04-talking-about-housing.md"""
    name = f"unit-{spec['unit']:02d}-{slug(spec['title']['en'])}.md"
    return STUDY_ROOT / spec["book"] / spec.get("kind", "grammar") / name


def check_pinyin_rule(md: str) -> list[str]:
    """Every line with Chinese must carry pinyin (same line or the next one)."""
    problems = []
    lines = md.splitlines()
    for i, l in enumerate(lines):
        if not re.search(r"[㐀-鿿]", l) or l.startswith("<details"):
            continue
        nxt = lines[i + 1] if i + 1 < len(lines) else ""
        has = ("<rt>" in l) or re.search(r"[āáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜ]", l + nxt) or re.search(r"\((?:[a-zü]+\s?)+\)", l)
        if not has:
            problems.append(f"line {i + 1}: {l[:80]}")
    return problems


# ------------------------------------------------------------------------ main

def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("sections"); s.add_argument("book"); s.add_argument("unit", nargs="?", type=int)
    t = sub.add_parser("text"); t.add_argument("book"); t.add_argument("first", type=int); t.add_argument("last", nargs="?", type=int)
    im = sub.add_parser("images"); im.add_argument("book"); im.add_argument("first", type=int)
    im.add_argument("last", nargs="?", type=int); im.add_argument("--dpi", type=int, default=60)
    im.add_argument("--out", type=Path, default=paths.CACHE / "_pages")
    py = sub.add_parser("pinyin"); py.add_argument("text", nargs="+")
    r = sub.add_parser("render"); r.add_argument("specs", nargs="+", type=Path)
    r.add_argument("--show-generated", action="store_true", help="list pinyin that was generated (to review)")
    a = ap.parse_args()

    if a.cmd == "sections":
        printed = printed_numbers(a.book)
        units = [a.unit] if a.unit else list(unit_starts(a.book))
        for u in units:
            first, last = unit_range(a.book, u)
            print(f"Unit {u}: PDF pages {first}-{last}")
            for name, p in sections(a.book, u):
                pr = f" (printed p. {printed[p]})" if p in printed else ""
                print(f"   p{p:>4}{pr:<20} {name}")
    elif a.cmd == "text":
        texts = page_texts(a.book)
        for p in range(a.first, (a.last or a.first) + 1):
            print(f"===== PDF page {p} =====\n{texts.get(p, '')}")
    elif a.cmd == "images":
        import pymupdf
        a.out.mkdir(parents=True, exist_ok=True)
        with pymupdf.open(paths.TEXTBOOKS / f"{a.book}.pdf") as doc:
            for p in range(a.first, (a.last or a.first) + 1):
                f = a.out / f"{a.book.replace(' ', '_')}_p{p:04d}.png"
                doc[p - 1].get_pixmap(dpi=a.dpi).save(f)
                print(f)
    elif a.cmd == "pinyin":
        import pinyin_util
        for t in a.text:
            print(pinyin_util.sentence_pinyin(t))
    elif a.cmd == "render":
        for sp in a.specs:
            spec = json.loads(sp.read_text(encoding="utf-8"))
            GENERATED.clear()
            RUBY_FAILS.clear()
            md = render_spec(spec)
            for zh_f, py_f in dict.fromkeys(RUBY_FAILS):
                print(f"   ! pinyin doesn't align, shown on its own line: {zh_f}  |  {py_f}")
            if a.show_generated:
                for zh, py in dict.fromkeys(GENERATED):
                    if len(zh) > 1:
                        print(f"   {zh}  ->  {py}")
            dest = out_path(spec)
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(md, encoding="utf-8")
            probs = check_pinyin_rule(md)
            print(f"{sp} -> {dest}" + (f"  ({len(probs)} lines missing pinyin)" if probs else ""))
            for pr in probs[:10]:
                print("   ", pr)


if __name__ == "__main__":
    main()
